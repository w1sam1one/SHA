#!/usr/bin/env python3
"""Writes assets/licenses/rust.txt: the licenses of the Rust crates that are
built into the app's Olm library (flutter_vodozemac's rust/ crate) for
Android.

Run after `flutter pub get`, with cargo installed:
    python3 tool/rust_licenses.py

It uses the plugin's own Cargo.lock (cargo metadata --locked) and keeps only
the normal dependencies that are built for the four Android targets. Each
crate's own license files are included; identical texts are given once,
with every crate that uses them.
"""
import hashlib
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGETS = [
    "aarch64-linux-android",
    "armv7-linux-androideabi",
    "x86_64-linux-android",
    "i686-linux-android",
]
LICENSE_PREFIXES = ("license", "licence", "copying", "notice", "unlicense")


def plugin_manifest():
    config = json.loads((ROOT / ".dart_tool/package_config.json").read_text())
    for p in config["packages"]:
        if p["name"] == "flutter_vodozemac":
            root = p["rootUri"]
            path = pathlib.Path(root[len("file://"):] if root.startswith("file://") else ROOT / ".dart_tool" / root)
            return (path / "rust/Cargo.toml").resolve()
    sys.exit("flutter_vodozemac not found: run flutter pub get first")


def metadata(manifest, target):
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked",
         "--manifest-path", str(manifest), "--filter-platform", target],
        check=True, capture_output=True, text=True).stdout
    return json.loads(out)


def built(meta):
    """Package ids reachable from the root through normal dependencies."""
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    todo, seen = [meta["resolve"]["root"]], set()
    while todo:
        pid = todo.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]):
                todo.append(dep["pkg"])
    return seen


def main():
    manifest = plugin_manifest()
    packages, ids = {}, set()
    for target in TARGETS:
        meta = metadata(manifest, target)
        packages.update({p["id"]: p for p in meta["packages"]})
        ids |= built(meta)
    texts = {}  # sha256 -> (text, [crate names])
    listed, no_file = [], []
    for pid in sorted(ids, key=lambda i: (packages[i]["name"], packages[i]["version"])):
        p = packages[pid]
        name = f'{p["name"]} {p["version"]}'
        listed.append(f'{name}: {p.get("license") or "see the text below"}')
        folder = pathlib.Path(p["manifest_path"]).parent
        files = sorted(f for f in folder.iterdir()
                       if f.is_file() and f.name.lower().startswith(LICENSE_PREFIXES))
        if p.get("license_file"):
            files.append(folder / p["license_file"])
        if not files:
            no_file.append(f'{name}: {p.get("license")}, {p.get("repository") or "no repository given"}')
        for f in dict.fromkeys(files):
            text = f.read_text(errors="replace").strip()
            key = hashlib.sha256(text.encode()).hexdigest()
            texts.setdefault(key, (text, []))[1].append(name)
    out = ROOT / "assets/licenses/rust.txt"
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w") as w:
        w.write("Rust crates in the Olm library (flutter_vodozemac) for Android\n")
        w.write("Generated by tool/rust_licenses.py from the plugin's Cargo.lock.\n\n")
        w.write("\n".join(listed) + "\n")
        if no_file:
            w.write("\nNo license file in the published crate (license from Cargo.toml):\n")
            w.write("\n".join(no_file) + "\n")
        for text, names in texts.values():
            w.write("\n" + "=" * 72 + "\n")
            w.write("Used by: " + ", ".join(names) + "\n\n")
            w.write(text + "\n")
    print(f"{out.relative_to(ROOT)}: {len(listed)} crates, {len(texts)} texts")


if __name__ == "__main__":
    main()
